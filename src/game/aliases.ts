/**
 * Выдать псевдоним, которого ещё ни у кого нет.
 *
 * @param taken   Уже занятые псевдонимы (сравнение без учёта регистра).
 * @param random  Источник случайности. Отдельным параметром, чтобы тест мог
 *   задать предсказуемый выбор, не подменяя глобальный Math.random.
 */
export function pickAlias(taken: Iterable<string>, random: () => number = Math.random): string {
  const used = new Set<string>();
  for (const t of taken) {
    if (typeof t === "string" && t.trim()) used.add(t.trim().toLowerCase());
  }

  const free = ALIAS_POOL.filter((a) => !used.has(a.toLowerCase()));
  if (free.length > 0) {
    return free[Math.floor(random() * free.length) % free.length];
  }

  /*
   * Герои кончились. Добавляем номер к случайному имени, но НЕ хендл: смысл
   * псевдонима в том, чтобы настоящий аккаунт не попал на экран другим
   * игрокам ни при каких обстоятельствах.
   */
  for (let suffix = 2; suffix < 1000; suffix++) {
    for (const base of ALIAS_POOL) {
      const candidate = `${base} ${suffix}`;
      if (!used.has(candidate.toLowerCase())) return candidate;
    }
  }

  // Практически недостижимо: это больше ста тысяч игроков.
  return `Герой ${Date.now()}`;
}

/**
 * Похоже ли это на Telegram-хендл.
 *
 * Нужно там, где псевдоним обязан быть, но данные пришли из старого
 * состояния: «@user» показывать другим игрокам нельзя.
 */
export function looksLikeHandle(value: string | undefined | null): boolean {
  return typeof value === "string" && value.trim().startsWith("@");
}

/**
 * Имя игрока, которое разрешено показывать остальным.
 *
 * Псевдоним, если он есть. Иначе — заглушка: лучше безликое «Игрок», чем
 * утёкший хендл.
 */
export function publicName(player: { alias?: string; name?: string }): string {
  const alias = player.alias?.trim();
  if (alias) return alias;
  if (player.name && !looksLikeHandle(player.name)) return player.name;
  return "Игрок";
}
