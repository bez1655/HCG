export function pickAlias(taken: Iterable<string>, random: () => number = Math.random): string {
  const used = new Set<string>();
  for (const t of taken) {
    if (typeof t === "string" && t.trim()) used.add(t.trim().toLowerCase());
  }

  const free = ALIAS_POOL.filter((a) => !used.has(a.toLowerCase()));
  if (free.length > 0) {
    return free[Math.floor(random() * free.length) % free.length];
  }

  for (let suffix = 2; suffix < 1000; suffix++) {
    for (const base of ALIAS_POOL) {
      const candidate = `${base} ${suffix}`;
      if (!used.has(candidate.toLowerCase())) return candidate;
    }
  }

  return `Киногерой ${Date.now()}`;
}

export function looksLikeHandle(value: string | undefined | null): boolean {
  return typeof value === "string" && value.trim().startsWith("@");
}

export function publicName(player: { alias?: string; name?: string }): string {
  const alias = player.alias?.trim();
  if (alias) return alias;
  if (player.name && !looksLikeHandle(player.name)) return player.name;
  return "Игрок";
}

const MOVIE_ROOTS = new Set(ALIAS_POOL.map((a) => a.toLowerCase()));

/** True when the public alias already belongs to the movie characters pool (or "Name 2"). */
export function isMovieAlias(alias: string | undefined | null): boolean {
  if (!alias || !alias.trim()) return false;
  const t = alias.trim().toLowerCase();
  if (MOVIE_ROOTS.has(t)) return true;
  const m = t.match(/^(.*) (\d+)$/);
  return Boolean(m && MOVIE_ROOTS.has(m[1]));
}

/** Сохраняем имя для обратной совместимости вызовов. */
export const isHorrorAlias = isMovieAlias;

export function takenMovieNames(
  players: { alias?: string; pendingMovieAlias?: string; pendingHorrorAlias?: string }[]
): string[] {
  const out: string[] = [];
  for (const p of players) {
    if (p.pendingMovieAlias) out.push(p.pendingMovieAlias);
    if (p.pendingHorrorAlias) out.push(p.pendingHorrorAlias);
    if (p.alias && isMovieAlias(p.alias)) out.push(p.alias);
  }
  return out;
}

/** Сохраняем имя для обратной совместимости вызовов. */
export const takenHorrorNames = takenMovieNames;
