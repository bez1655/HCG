import { describe, it, expect } from "vitest";
import { findMentions } from "./mentions";

/**
 * Поиск упоминаний в сообщении администратора.
 *
 * Цена ошибки в обе стороны: не найти названного — админ решит, что игрок
 * получил сообщение, а тот ничего не увидит. Найти лишнего — человек получит
 * в личку чужое обращение.
 */
const players = [
  { id: "p1", alias: "Бэтмен", name: "@real_bat" },
  { id: "p2", alias: "Тор", name: "@real_thor" },
  { id: "p3", alias: "Гарри Поттер", name: "@real_harry" },
  { id: "p4", alias: "Йода", name: "@real_yoda" },
];

const ids = (text: string) => findMentions(text, players).map((p) => p.id);

describe("находит названного игрока", () => {
  it("по псевдониму в начале сообщения", () => {
    expect(ids("Бэтмен, зайдите за призом")).toEqual(["p1"]);
  });

  it("в середине предложения", () => {
    expect(ids("Сегодня Тор получает награду")).toEqual(["p2"]);
  });

  it("не обращая внимания на регистр", () => {
    expect(ids("бэтмен, приз готов")).toEqual(["p1"]);
    expect(ids("ЙОДА зайдите")).toEqual(["p4"]);
  });

  it("составной псевдоним из двух слов", () => {
    expect(ids("Гарри Поттер, ваш приз ждёт")).toEqual(["p3"]);
  });

  it("нескольких сразу", () => {
    expect(ids("Бэтмен и Тор, подойдите оба").sort()).toEqual(["p1", "p2"]);
  });

  it("рядом со знаками препинания", () => {
    expect(ids("(Тор) — заберите приз")).toEqual(["p2"]);
    expect(ids("Приз для: Йода!")).toEqual(["p4"]);
  });
});

describe("не находит лишнего", () => {
  it("не срабатывает внутри другого слова", () => {
    /*
     * «Тор» внутри «Торт» — самая опасная ошибка: короткие псевдонимы вроде
     * «Тор», «Рей», «Сэм» встречаются в обычных словах.
     */
    expect(ids("Купите торт к празднику")).toEqual([]);
    expect(ids("Сегодня ретортный день")).toEqual([]);
  });

  it("молчит, когда никого не назвали", () => {
    expect(ids("Всем добрый день, игра продолжается")).toEqual([]);
  });

  it("не шлёт одному человеку дважды", () => {
    // Иначе игрок получит два одинаковых сообщения подряд.
    expect(ids("Бэтмен, Бэтмен, ответьте")).toEqual(["p1"]);
  });

  it("не спотыкается о пустое сообщение", () => {
    expect(findMentions("", players)).toEqual([]);
  });

  it("не падает без игроков", () => {
    expect(findMentions("Бэтмен", [])).toEqual([]);
  });
});

describe("настоящий хендл тоже работает", () => {
  it("админ может назвать игрока по его @хендлу", () => {
    // Админ видит настоящие хендлы и может привыкнуть к ним.
    expect(ids("@real_bat зайдите за призом")).toEqual(["p1"]);
  });
});

describe("устойчивость", () => {
  it("не ломается на спецсимволах в псевдониме", () => {
    // Админ мог переименовать игрока во что угодно.
    const odd = [{ id: "x", alias: "Ц-3ПО (бета)" }];
    expect(findMentions("Ц-3ПО (бета), проверьте", odd).map((p) => p.id)).toEqual(["x"]);
  });

  it("игнорирует слишком короткие имена", () => {
    // Односимвольное имя совпало бы со всем подряд.
    const odd = [{ id: "x", alias: "О" }];
    expect(findMentions("Отличная погода", odd)).toEqual([]);
  });
});
