#!/data/data/com.termux/files/usr/bin/bash
# =============================================================================
#  HCG — развернуть игру на сервере, из Termux
# =============================================================================
#  Где запускать: Termux на телефоне
#  Как:  bash termux/1-СЕРВЕР.sh
#
#  Скрипт НЕ разворачивает игру на телефоне — он подключается к вашему серверу
#  по SSH и запускает установку там. Телефон здесь вместо ноутбука.
#
#  Что делает:
#    • ставит недостающие пакеты (openssh)
#    • копирует архив проекта на сервер
#    • запускает на сервере штатный установщик
# =============================================================================

set -uo pipefail

G=$'\e[32m'; R=$'\e[31m'; Y=$'\e[33m'; C=$'\e[36m'; B=$'\e[1m'; N=$'\e[0m'
ok()   { echo "  ${G}✓${N} $*"; }
bad()  { echo "  ${R}✗${N} $*"; }
warn() { echo "  ${Y}!${N} $*"; }
hdr()  { echo; echo "${B}${C}▸ $*${N}"; }
die()  { echo; echo "${R}${B}ОСТАНОВЛЕНО: $*${N}"; echo; exit 1; }

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CFG="$HOME/.hcg-termux"

echo "${B}╔════════════════════════════════════════════╗${N}"
echo "${B}║  HCG — установка на сервер из Termux       ║${N}"
echo "${B}╚════════════════════════════════════════════╝${N}"

# ---------------------------------------------------------------------------
hdr "1/5  Проверка Termux"
# ---------------------------------------------------------------------------
[ -d "/data/data/com.termux" ] || warn "похоже, это не Termux — скрипт рассчитан на него"

if ! command -v ssh >/dev/null 2>&1; then
  echo "  Ставлю openssh (нужен для подключения к серверу)..."
  pkg install -y openssh >/dev/null 2>&1 || die "не удалось установить openssh"
fi
ok "ssh на месте"

command -v tar >/dev/null 2>&1 || pkg install -y tar >/dev/null 2>&1
ok "tar на месте"

[ -f "$ROOT/docker-compose.yml" ] || die "запускайте из распакованного архива проекта"
[ -f "$ROOT/deploy/1-СЕРВЕР.sh" ] || die "в архиве нет установщика deploy/1-СЕРВЕР.sh"
ok "файлы проекта найдены"

# ---------------------------------------------------------------------------
hdr "2/5  Данные сервера"
# ---------------------------------------------------------------------------
# Запоминаем, чтобы не вводить каждый раз.
if [ -f "$CFG" ]; then
  # shellcheck disable=SC1090
  . "$CFG"
  ok "сохранённый сервер: ${SSH_USER}@${SSH_HOST}"
  printf "  Использовать его? [Д/н] "
  read -r keep
  case "$keep" in
    [nNнН]*) SSH_HOST=""; SSH_USER="" ;;
  esac
fi

if [ -z "${SSH_HOST:-}" ]; then
  printf "  Адрес сервера (например VM-744336 или 1.2.3.4): "
  read -r SSH_HOST
  printf "  Пользователь [root]: "
  read -r SSH_USER
  SSH_USER="${SSH_USER:-root}"
  printf "  Порт SSH [22]: "
  read -r SSH_PORT
  SSH_PORT="${SSH_PORT:-22}"

  {
    echo "SSH_HOST=$SSH_HOST"
    echo "SSH_USER=$SSH_USER"
    echo "SSH_PORT=$SSH_PORT"
  } > "$CFG"
  chmod 600 "$CFG"
  ok "данные сохранены в $CFG"
fi
SSH_PORT="${SSH_PORT:-22}"

# ---------------------------------------------------------------------------
hdr "3/5  Проверка связи"
# ---------------------------------------------------------------------------
echo "  Подключаюсь к ${SSH_USER}@${SSH_HOST}:${SSH_PORT}..."
echo "  ${Y}Пароль сервера будет запрошен несколько раз — это нормально.${N}"
echo

if ! ssh -p "$SSH_PORT" -o ConnectTimeout=15 -o StrictHostKeyChecking=accept-new \
     "${SSH_USER}@${SSH_HOST}" "echo ok" >/dev/null 2>&1; then
  bad "не удалось подключиться"
  echo
  echo "  Проверьте:"
  echo "    • адрес и пользователь введены верно;"
  echo "    • сервер включён и доступен из интернета;"
  echo "    • на телефоне есть сеть."
  echo
  echo "  Чтобы не вводить пароль каждый раз, настройте ключ:"
  echo "      ssh-keygen -t ed25519"
  echo "      ssh-copy-id -p $SSH_PORT ${SSH_USER}@${SSH_HOST}"
  die "нет связи с сервером"
fi
ok "сервер отвечает"

# ---------------------------------------------------------------------------
hdr "4/5  Отправка проекта"
# ---------------------------------------------------------------------------
STAMP="$(date +%Y%m%d-%H%M%S)"
REMOTE_DIR="/root/hcg-upload-$STAMP"

echo "  Упаковываю и отправляю (может занять минуту)..."

# Через tar по конвейеру: одна передача вместо тысяч мелких файлов,
# и не нужен установленный на сервере unzip.
if tar -C "$ROOT" \
      --exclude=node_modules --exclude=.git --exclude=dist \
      --exclude=apk/node_modules --exclude=apk/www --exclude=apk/android \
      -czf - . 2>/dev/null \
   | ssh -p "$SSH_PORT" "${SSH_USER}@${SSH_HOST}" \
       "mkdir -p '$REMOTE_DIR' && tar -xzf - -C '$REMOTE_DIR'"; then
  ok "проект загружен в $REMOTE_DIR"
else
  die "не удалось отправить файлы"
fi

# ---------------------------------------------------------------------------
hdr "5/5  Установка на сервере"
# ---------------------------------------------------------------------------
echo "  Запускаю установщик. Дальше всё происходит на сервере."
echo "  ${Y}Это займёт 5–10 минут (сборка образов).${N}"
echo

ssh -p "$SSH_PORT" -t "${SSH_USER}@${SSH_HOST}" \
  "cd '$REMOTE_DIR' && bash deploy/1-СЕРВЕР.sh"
RESULT=$?

echo
if [ $RESULT -eq 0 ]; then
  echo "${G}${B}╔════════════════════════════════════════════╗${N}"
  echo "${G}${B}║  ГОТОВО. Игра развёрнута.                  ║${N}"
  echo "${G}${B}╚════════════════════════════════════════════╝${N}"
  cat <<'NEXT'

  Дальше — два действия в Telegram:

    1. Отправьте боту НОВУЮ команду /start
       (в старом сообщении кнопки не меняются)
    2. Проверьте /pending

NEXT
else
  bad "установщик завершился с ошибкой — смотрите вывод выше"
  echo "  Подключиться и разобраться:"
  echo "      ssh -p $SSH_PORT ${SSH_USER}@${SSH_HOST}"
fi

exit $RESULT
