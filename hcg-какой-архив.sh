#!/usr/bin/env bash
# =============================================================================
#  Какой архив реально распаковался
# =============================================================================
#  Запускать НА СЕРВЕРЕ:  bash hcg-какой-архив.sh
#
#  Отвечает на один вопрос: почему в hcg-new оказалась не та сборка.
#  Причина почти всегда в том, что распакован НЕ ТОТ ФАЙЛ — старый архив
#  с тем же именем лежит в другом каталоге, либо scp положил новый рядом,
#  а unzip взял прежний.
# =============================================================================

set -uo pipefail

G=$'\e[32m'; R=$'\e[31m'; Y=$'\e[33m'; C=$'\e[36m'; B=$'\e[1m'; N=$'\e[0m'
ok()   { echo "  ${G}✓${N} $*"; }
bad()  { echo "  ${R}✗${N} $*"; }
warn() { echo "  ${Y}!${N} $*"; }
hdr()  { echo; echo "${B}${C}▸ $*${N}"; }

echo "${B}╔════════════════════════════════════════════╗${N}"
echo "${B}║  Какой архив распаковался                  ║${N}"
echo "${B}╚════════════════════════════════════════════╝${N}"

EXPECTED="2026-08-05.6"

# ---------------------------------------------------------------------------
hdr "1/4  Все архивы HCG на сервере"
# ---------------------------------------------------------------------------
# Ищем по всему диску: файл с одним и тем же именем в двух каталогах —
# самая частая причина «пришла старая сборка».
FOUND=0
while IFS= read -r z; do
  FOUND=$((FOUND + 1))
  SIZE=$(du -h "$z" 2>/dev/null | cut -f1)
  WHEN=$(stat -c '%y' "$z" 2>/dev/null | cut -c1-16)

  # Читаем метку сборки ПРЯМО ИЗ АРХИВА, не распаковывая его целиком.
  MARK=$(unzip -p "$z" bot/src/version.ts 2>/dev/null | grep -o 'BUILD = "[^"]*"' | head -1 | sed 's/.*"\(.*\)"/\1/')
  [ -z "$MARK" ] && MARK="(не читается)"

  if [ "$MARK" = "$EXPECTED" ]; then
    ok "$z"
    echo "       $SIZE, $WHEN, сборка ${B}${MARK}${N} ← ЭТОТ НУЖЕН"
  else
    warn "$z"
    echo "       $SIZE, $WHEN, сборка ${R}${MARK}${N} ← старый"
  fi
done < <(find / -maxdepth 5 -name "HCG*.zip" -type f 2>/dev/null | sort)

[ "$FOUND" = 0 ] && bad "архивов HCG на сервере не найдено — файл не залит"

# ---------------------------------------------------------------------------
hdr "2/4  Что лежит в hcg-new"
# ---------------------------------------------------------------------------
for D in /var/www/hcg-new /var/www/hcg; do
  if [ -f "$D/bot/src/version.ts" ]; then
    M=$(grep -o 'BUILD = "[^"]*"' "$D/bot/src/version.ts" | head -1 | sed 's/.*"\(.*\)"/\1/')
    W=$(stat -c '%y' "$D/bot/src/version.ts" 2>/dev/null | cut -c1-16)
    if [ "$M" = "$EXPECTED" ]; then
      ok "$D — сборка ${B}${M}${N}, файл от $W"
    else
      bad "$D — сборка ${R}${M}${N}, ожидалась $EXPECTED"
    fi
  else
    warn "$D — нет каталога или файла версии"
  fi
done

# ---------------------------------------------------------------------------
hdr "3/4  Новые файлы — есть или нет"
# ---------------------------------------------------------------------------
# Проверяем по существованию файлов, а не по метке: так видно, какая
# именно часть не доехала.
D=/var/www/hcg-new
if [ -d "$D" ]; then
  [ -f "$D/proxy-harvester/src/lease.ts" ] \
    && ok "аренда прокси на месте" || bad "нет proxy-harvester/src/lease.ts"
  [ -f "$D/bot/src/leaseClient.ts" ] \
    && ok "клиент аренды у бота на месте" || bad "нет bot/src/leaseClient.ts"

  ICON=$(stat -c%s "$D/apk/resources/icon.png" 2>/dev/null || echo 0)
  [ "$ICON" = "1200924" ] \
    && ok "иконка новая ($ICON байт)" || bad "иконка НЕ новая ($ICON байт, нужно 1200924)"

  DICE=$(stat -c%s "$D/public/Dice.png" 2>/dev/null || echo 0)
  [ "$DICE" = "554496" ] \
    && ok "кнопка броска новая ($DICE байт)" || bad "кнопка броска НЕ новая ($DICE байт, нужно 554496)"

  BG=$(stat -c%s "$D/public/BoardHAP.png" 2>/dev/null || echo 0)
  [ "$BG" = "522358" ] \
    && ok "фон новый ($BG байт)" || bad "фон НЕ новый ($BG байт, нужно 522358)"
else
  warn "каталога /var/www/hcg-new нет"
fi

# ---------------------------------------------------------------------------
hdr "4/4  Что делать"
# ---------------------------------------------------------------------------
cat <<INSTR

  Если выше нашлось несколько архивов и распаковался старый — удалите
  все старые и распакуйте заново, указав путь ПОЛНОСТЬЮ:

      ${B}rm -rf /var/www/hcg-new${N}
      ${B}find / -maxdepth 5 -name 'HCG*.zip' -delete${N}

  затем на Windows (PowerShell) залейте свежий файл:

      ${B}scp "\$env:USERPROFILE\\Downloads\\HCG-VPS.zip" root@VM-744336:/root/${N}

  и на сервере:

      ${B}cd /var/www && mkdir -p hcg-new && unzip -o /root/HCG-VPS.zip -d hcg-new${N}
      ${B}grep BUILD hcg-new/bot/src/version.ts${N}

  Последняя команда должна показать: ${B}${EXPECTED}${N}
  Если показывает другое — распаковался не тот файл, ищите его выше.

INSTR
